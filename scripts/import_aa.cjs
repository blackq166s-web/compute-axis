const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { parseArgs } = require('node:util');

const origin = 'https://artificialanalysis.ai';
const site = path.resolve(__dirname, '..');
const bundledSnapshot = path.join(site, 'aa-official-data.js');
const output = process.env.AA_STATE_FILE || bundledSnapshot;
const header = '// Generated by scripts/import_aa.cjs for internal preview.\nconst AA_OFFICIAL_DATA = ';
const catalog = vm.runInNewContext(
  fs.readFileSync(path.join(site, 'aa-chart-data.js'), 'utf8') + '\nAA_CHART_DATA.models',
);
const capabilityFields = [
  'finance_and_accounting', 'strategy_and_ops', 'legal',
  'healthcare_and_medical', 'engineering', 'economics',
].map(domain => `artificial_analysis_${domain}_index`);

function normalizeName(name) {
  return typeof name === 'string' ? name.trim().toLowerCase() : '';
}

const catalogNames = new Map(catalog.map(model => [
  normalizeName(model.effort ? `${model.name} (${model.effort})` : model.name), model,
]));

function numberOrNull(value) {
  return Number.isFinite(value) && value >= 0 ? value : null;
}

function chinaDate() {
  return new Intl.DateTimeFormat('sv-SE', { timeZone: 'Asia/Shanghai' }).format(new Date());
}

async function* getModelPages(tier, key) {
  if (!key) throw new Error('当前进程缺少 AA_API_KEY。');
  const route = tier === 'pro' ? '/api/v2/language/models' : '/api/v2/language/models/free';
  const deadline = AbortSignal.timeout(60000);
  let version;
  let totalPages;
  for (let page = 1; totalPages == null || page <= totalPages; page++) {
    const response = await fetch(`${origin}${route}?page=${page}`, {
      headers: { 'x-api-key': key, Accept: 'application/json' },
      redirect: 'error',
      signal: AbortSignal.any([deadline, AbortSignal.timeout(20000)]),
    });
    if (!response.ok) throw new Error(`AA API 返回 HTTP ${response.status}（第 ${page} 页）。`);
    const result = await response.json();
    const pagination = result.pagination;
    if (!Array.isArray(result.data) || !Number.isFinite(result.intelligence_index_version) ||
        pagination?.page !== page || !Number.isInteger(pagination.total_pages) ||
        pagination.total_pages < page || pagination.has_more !== (page < pagination.total_pages)) {
      throw new Error('AA API 响应不符合文档中的分页或版本格式。');
    }
    version ??= result.intelligence_index_version;
    totalPages ??= pagination.total_pages;
    if (version !== result.intelligence_index_version || totalPages !== pagination.total_pages) {
      throw new Error('分页期间 AA 快照已变化，请重新导入。');
    }
    yield result;
  }
}

async function loadApi(tier, key) {
  const models = new Map();
  let version;
  for await (const result of getModelPages(tier, key)) {
    version = result.intelligence_index_version;
    for (const row of result.data) {
      const match = catalogNames.get(normalizeName(row.name));
      if (!match) continue;
      if (models.has(match.id) || typeof row.id !== 'string' || !/^[a-z0-9-]+$/.test(row.slug ?? '')) {
        throw new Error(`无法确认唯一的 AA 型号与推理档位：${match.id}。`);
      }
      const seconds = numberOrNull(row.performance_v3?.time_per_task_seconds);
      models.set(match.id, {
        id: match.id,
        aaId: row.id,
        slug: row.slug,
        weight: match.weight && row.licensing?.is_open_weights !== false,
        score: numberOrNull(row.evaluations?.artificial_analysis_intelligence_index),
        cost: numberOrNull(row.artificial_analysis_intelligence_index_cost?.cost_per_task?.total_cost),
        minutes: seconds == null ? null : seconds / 60,
        capabilityScores: capabilityFields.map(field => numberOrNull(row.evaluations?.[field])),
      });
    }
  }
  if (!models.size || ![...models.values()].some(model => model.weight && model.score != null)) {
    throw new Error('AA API 没有匹配到可核验的本地模型评分，保留当前数据。');
  }
  return { indexVersion: version, readDate: chinaDate(), models: [...models.values()] };
}

function modelSource(value) {
  const source = new URL(value);
  if (source.origin !== origin || !/^\/models(?:\/|$)/.test(source.pathname) ||
      source.username || source.password) {
    throw new Error('Token 来源须是 AA 官方模型页面。');
  }
  return source.href;
}

function loadTokenUse(file, api) {
  const input = JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
  const source = modelSource(input.source);
  if (input.metric !== 'output-tokens-per-intelligence-index-task' ||
      !/^v\d+\.\d+(?:\.\d+)?$/.test(input.indexVersion ?? '') ||
      !/^\d{4}-\d{2}-\d{2}$/.test(input.readDate ?? '') ||
      !['comparison', 'export'].includes(input.kind) ||
      !Array.isArray(input.models) || !input.models.length) {
    throw new Error('缺少 AA 单任务 Token 指标、版本、采集日期或来源。');
  }
  const seen = new Set();
  const models = input.models.map(row => {
    const match = catalogNames.get(normalizeName(row.name));
    const official = api?.models.find(model => model.id === match?.id);
    const expectedSlug = official?.slug ?? match?.source?.split('/').at(-1);
    const tokens = numberOrNull(row.tokens);
    if (!match || seen.has(match.id) || tokens == null || !/^[a-z0-9-]+$/.test(row.slug ?? '') ||
        (row.defaultFallback === true && !match.rankEffort) ||
        (expectedSlug && row.slug !== expectedSlug)) {
      throw new Error('Token 文件含未知型号、档位不符、重复型号或无效数值。');
    }
    seen.add(match.id);
    return {
      id: match.id, slug: row.slug, tokens, source: row.source ? modelSource(row.source) : source,
      ...(row.defaultFallback === true ? { defaultFallback: true } : {}),
    };
  });
  return {
    indexVersion: input.indexVersion, readDate: input.readDate, kind: input.kind, source,
    models,
  };
}

function readSnapshot({ allowMissing = false } = {}) {
  let previous;
  let source;
  for (const file of new Set([output, bundledSnapshot])) {
    try {
      previous = fs.readFileSync(file, 'utf8');
      source = file;
      break;
    } catch (error) {
      if (error.code !== 'ENOENT' || (output === bundledSnapshot && !allowMissing)) throw error;
    }
  }
  if (previous === undefined) return {};
  if (path.extname(source) === '.json') return JSON.parse(previous);
  previous = previous.replace(/\r\n/g, '\n').trimEnd();
  if (!previous.startsWith(header) || !previous.endsWith(';')) throw new Error('当前 AA 数据文件格式异常。');
  return JSON.parse(previous.slice(header.length, -1));
}

function snapshotScript(snapshot) {
  return header + JSON.stringify(snapshot, null, 2) + ';\n';
}

function clientSnapshotScript({ baseline, ...snapshot }) {
  const baselineScript = baseline ? `Object.assign(AA_CHART_DATA, ${JSON.stringify(baseline)});\n` : '';
  return baselineScript + snapshotScript(snapshot);
}

function writeSnapshot(snapshot) {
  const temporary = `${output}.${process.pid}.tmp`;
  try {
    const content = path.extname(output) === '.json'
      ? JSON.stringify(snapshot, null, 2) + '\n' : snapshotScript(snapshot);
    fs.writeFileSync(temporary, content, { flag: 'wx', mode: 0o600 });
    fs.renameSync(temporary, output);
  } finally {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
  }
}

async function main() {
  const { values } = parseArgs({ options: { api: { type: 'string' }, tokens: { type: 'string' } } });
  if ((!values.api && !values.tokens) || (values.api && !['free', 'pro'].includes(values.api))) {
    throw new Error('用法：node scripts/import_aa.cjs [--api free|pro] [--tokens AA单任务Token.json]');
  }
  const api = values.api ? await loadApi(values.api, process.env.AA_API_KEY?.trim()) : null;
  const snapshot = readSnapshot();
  if (values.api) snapshot.api = api;
  if (values.tokens) snapshot.tokenUse = loadTokenUse(values.tokens, snapshot.api);
  writeSnapshot(snapshot);
  const models = snapshot.api?.models ?? [];
  const rated = models.filter(model => model.capabilityScores.every(score => score != null));
  console.log(`AA API 匹配 ${models.length} 个型号，其中 ${models.filter(model => model.weight).length} 个本地型号。`);
  console.log(`六领域完整 ${rated.length} 个，其中 ${rated.filter(model => model.weight).length} 个本地型号。`);
  console.log(`单任务输出 Token ${snapshot.tokenUse?.models.length ?? 0} 个型号。`);
}

if (require.main === module) {
  main().catch(error => {
    console.error(`AA 导入失败，原数据已保留。${error.message}`);
    process.exitCode = 1;
  });
}

module.exports = {
  clientSnapshotScript, getModelPages, loadApi, normalizeName, numberOrNull,
  readSnapshot, snapshotScript, writeSnapshot,
};
