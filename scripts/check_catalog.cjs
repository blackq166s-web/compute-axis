const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),context={};
vm.createContext(context);
vm.runInContext(['flopper-data.js','data.js'].map(f=>fs.readFileSync(path.join(root,f),'utf8')).join('\n')+'\nthis.rows=HARDWARE;this.source=FLOPPER_SNAPSHOT.rows;this.iconMap=FLOPPER_SNAPSHOT.brandIcons;',context);
const {rows,source}=context;
assert.equal(rows.length,329);
for(const file of Object.values(context.iconMap||{}))assert(fs.existsSync(path.join(root,'assets/brands',file)));
assert.equal(new Set(rows.map(d=>d.id)).size,329);
assert.equal(rows.filter(d=>d.curated).length,26);
assert.equal(rows.filter(d=>d.type==='system').length,6);
assert.equal(rows.filter(d=>d.dataOrigin==='flopper').length,320);
assert.equal(source.find(d=>d.name==='Vera Rubin Superchip').bandwidth,44000);
assert.equal(source.find(d=>d.name==='Vera Rubin Superchip').acceleratorCount,2);
assert.equal(source.find(d=>d.name==='Rubin CPX').bandwidth,null);
assert.equal(source.find(d=>d.name==='ATOM-Max').acceleratorCount,4);
assert.equal(source.find(d=>d.name==='M5 Ultra').memoryKind,'unified');
assert.equal(new Set(source.map(d=>d.sourceRank)).size,320);
assert.equal(Math.max(...source.map(d=>d.sourceRank)),320);
assert.equal(source.find(d=>d.name==='H100 SXM5 80GB').rentalUsdHour,1.99);
assert.equal(source.filter(d=>d.rentalUsdHour!==null).length,52);
assert(rows.every(d=>d.price===null),'USD rental prices must never become CNY purchase prices');
assert.equal(rows.find(d=>d.id==='p6000').bandwidth,1790);
assert.equal(rows.find(d=>d.id==='p6000').previousReference.bandwidth,1792);
assert.equal(rows.find(d=>d.id==='s5000').memory,80);
assert.equal(rows.find(d=>d.id==='910c').memory,null,'Do not merge a generic series with a specific package');
assert(source.find(d=>d.name==='B300 SXM 262GB').sourceNotes.length>0,'Keep source conflicts visible');
for(const d of source){assert(d.source==='https://flopper.io/gpus');assert(d.capturedAt);assert(d.memory===null||d.memory>0);assert(d.rentalUsdHour===null||d.rentalUsdHour>0)}
console.log('Catalog checks passed: 329 records, 320 source rows, 26 curated entries, 6 systems, 52 rental prices.');
